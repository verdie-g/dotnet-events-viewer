    // Build the event index once. Payload selection must not scan/sort the manifest
    // or clone EventMetadata for every schema-less event.
    private static readonly Dictionary<int, Schema[]> SchemasById = Schemas
        .GroupBy(s => s.Key.Id)
        .ToDictionary(group => group.Key, group => group
            .OrderByDescending(s => s.Key.Version)
            .Select(s => new Schema(s.Key.Version, s.Value.Name, s.Value.Fields))
            .ToArray());

    internal readonly record struct Schema(int Version, string Name, EventFieldDefinition[] Fields);

    // Descending version order; RuntimePayloadReader moves the declared version
    // to the front once when compiling a candidate list.
    public static IReadOnlyList<Schema> Candidates(int eventId) =>
        SchemasById.TryGetValue(eventId, out var schemas) ? schemas : Array.Empty<Schema>();
